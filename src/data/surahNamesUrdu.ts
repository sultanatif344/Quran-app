const URDU_DIGITS = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹']

/** 123 → ۱۲۳ */
export function toUrduDigits(n: number | string): string {
  return String(n).replace(/\d/g, (d) => URDU_DIGITS[Number(d)])
}
